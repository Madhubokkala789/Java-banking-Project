Java Banking Management System

About the Project

A console-based Banking Management System developed using Core Java and Object-Oriented Programming principles.

Features

- Deposit money
- Withdraw money
- Check account balance
- View account details
- Exit the application

Technologies Used

- Core Java
- VS Code

OOP Concepts

- Encapsulation
- Inheritance
- Abstraction
- Polymorphism
- Constructors

